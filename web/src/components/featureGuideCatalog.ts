export function normalizeGuidePath(path: string) {
  const clean = String(path || '/')
    .split(/[?#]/, 1)[0]
    .replace(/\/+$/, '');
  return clean || '/';
}

export function canAccessFeatureGuide(guide: FeatureGuide, modules: string[], role?: string) {
  if (guide.roles && !guide.roles.includes(String(role || ''))) return false;
  if (guide.module && !modules.includes(guide.module)) return false;
  return role !== 'platform_super';
}

export function canAccessFeatureGuideContext(guide: FeatureGuide, contextKey?: string, role?: string) {
  const context = contextKey ? guide.contexts?.[contextKey] : undefined;
  if (!context?.roles) return true;
  return context.roles.includes(String(role || ''));
}

export function findFeatureGuide(path: string) {
  const normalized = normalizeGuidePath(path);
  return FEATURE_GUIDES.find(guide => {
    const routes = [guide.path, ...(guide.aliases || [])].map(normalizeGuidePath);
    if (routes.includes(normalized)) return true;
    return routes.some(route => route !== '/' && normalized.startsWith(`${route}/`));
  });
}

export function resolveFeatureGuideContext(guide: FeatureGuide, contextKey?: string, role?: string): FeatureGuide {
  const resolvedKey = contextKey || (role && guide.contexts?.[role] ? role : undefined);
  const context = resolvedKey ? guide.contexts?.[resolvedKey] : undefined;
  if (!context || !canAccessFeatureGuideContext(guide, resolvedKey, role)) return guide;
  const safeContext = { ...context };
  delete safeContext.roles;
  return { ...guide, ...safeContext };
}
