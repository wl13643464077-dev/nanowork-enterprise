// ===== 数字员工商业档案：老板视角的"花多少钱 → 产出什么 → 大约值多少" =====
// 估值口径：参考估值为行业经验区间，按"月营业额 30 万的单店"基准折算，
// 明确标注为参考信息，不构成平台承诺；单次成本与积分计费引擎实时对齐。
import { billing } from '../engines/credits.js';
import { textModelFor } from '../engines/yunwu.js';
import { curTenant, q } from '../db.js';

// 本企业真实结算中位数（最近 20 笔成功实扣的员工文本任务）。
// 有真实账本就用真实账本——理论估算在真实通道下会严重偏低（完整岗位快照+联网+修复重试）。
function settledMedianCredits() {
  try {
    const rows = q.all(`SELECT credits FROM credit_logs
      WHERE tenant_id=? AND kind='text' AND credits>0 AND input_tokens>0
        AND (feature LIKE '员工任务%' OR feature LIKE '内容员工%')
      ORDER BY id DESC LIMIT 20`, curTenant());
    if (rows.length < 3) return null;
    const sorted = rows.map(row => Number(row.credits)).sort((a, b) => a - b);
    return { median: sorted[Math.floor(sorted.length / 2)], samples: rows.length };
  } catch {
    return null;
  }
}

// 单次派活成本（积分）：按计费引擎当前价目实时计算，不写死数字。
// 口径：标准篇幅约 输入4000+输出2500 tokens；完整篇幅约 输入4000+输出8000 tokens。
function creditsFor(model, outTokens, b) {
  const p = b.text[model] || b.text.default;
  const yuan = (4000 / 1e6) * p.in + (outTokens / 1e6) * p.out;
  return Math.max(1, Math.ceil((yuan * b.marginMultiplier) / b.creditYuan));
}

export function taskCostBand(role = null) {
  const b = billing();
  const models = Object.keys(b.text).filter(key => key !== 'default');
  const lows = models.map(m => creditsFor(m, 2500, b));
  const highs = models.map(m => creditsFor(m, 8000, b));
  const min = Math.min(...lows);
  const max = Math.max(...highs);
  // 典型值优先用本企业真实结算中位数（诚实优先）；账本样本不足时才退回理论估算
  const roleModel = textModelFor(role === 'platform_super' ? 'boss' : role || 'sales');
  const actual = settledMedianCredits();
  const estimated = creditsFor(roleModel, 2500, b);
  const typicalCredits = actual ? actual.median : estimated;
  const typicalBasis = actual
    ? `按本企业最近 ${actual.samples} 次真实结算的中位数（含完整岗位快照与联网检索的实际用量）`
    : `按当前账号模型（${roleModel}）标准篇幅理论估算；真实任务含完整岗位快照与联网检索，实际结算通常更高，以账单为准`;
  return {
    minCredits: min,
    maxCredits: max,
    minYuan: Math.round(min * b.creditYuan * 100) / 100,
    maxYuan: Math.round(max * b.creditYuan * 100) / 100,
    typicalCredits,
    typicalYuan: Math.round(typicalCredits * b.creditYuan * 100) / 100,
    typicalBasis,
    note: '按实际 token 用量两阶段结算：先预授权，交付成功才实扣，未交付全额退回。',
  };
}

// 参考价值典型值：区间几何均值，取两位有效数字（比宽区间可读，且不夸大到上限）
function typicalValueOf(low, high) {
  const mid = Math.sqrt(low * high);
  const magnitude = 10 ** Math.floor(Math.log10(mid));
  return Math.round(mid / (magnitude / 10)) * (magnitude / 10);
}

